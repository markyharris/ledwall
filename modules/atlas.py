def _fmt_pop(v):
    if v >= 1e9:
        return "%.2fB" % (v / 1e9)
    if v >= 1e6:
        return "%dM" % round(v / 1e6)
    if v >= 1e3:
        return "%dK" % round(v / 1e3)
    return "%d" % v


def _fmt_density(v):
    if v >= 100:
        return "%s/km²" % format(int(round(v)), ",")
    return "%.1f/km²" % v


def _fmt_money(v):
    if v >= 1000:
        return "$%dK" % round(v / 1000)
    return "$%d" % v


def _fmt_pct(v):
    return "%d%%" % round(v)


def _fmt_years(v):
    return "%d YRS" % round(v)


def _fmt_int(v):
    return format(int(round(v)), ",")


