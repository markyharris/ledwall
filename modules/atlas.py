"""World in Numbers: the atlas module.

One module, one earth, a procession of statistics. Each
statistic fills every country from a color ramp - population,
density, wealth, forests, and the rest - with the scale in a
legend and the leaders named in the strip, holds for the
configured seconds, then crossfades to the next. The country
figures (Our World in Data's republication of the World Bank,
UN and ITU series) are baked into data/world_stats.json
(generated by ledwall-build/gen_world_stats.py, refreshed
yearly at most); the station counts come from the wall's own
baked directory; the earthquake counts are the one live
statistic, from the same USGS feed as the Earthquake Map,
counted into countries on the Pi.

Adding a statistic is a row in STATS plus, for a baked one, a
key in the generated data file.
"""
