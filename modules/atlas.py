def _lerp(lo, hi, t):
    return tuple(int(lo[i] + (hi[i] - lo[i]) * t) for i in range(3))


class AtlasModule(Module):
    name = "atlas"
    title = "World in Numbers"
    tick_s = 1
    PERSIST = ("quakes", "_qversion")

    def setup(self, config):
        self.cfg = config
        self.proj = Projection(get_region("WORLD")["bbox"])
        self.dot_count = 0
        self.t0 = time.time()
        self.quakes = None      # {country name: count}
        self._qversion = 0
        self._frames = {}       # (stat idx, qversion) -> image
        self._prepared = {}     # (stat key, qversion) -> render kit
        try:
            with open(os.path.join(render.DATA_DIR,
                                   "world_stats.json")) as f:
                doc = json.load(f)
            self.data = doc.get("stats", {})
            self.years = doc.get("meta", {}).get("years", {})
        except Exception:
            self.data = {}
            self.years = {}
        # per-country geometry, once: pixel rings for the fills,
        # lon/lat outer rings + bbox for the earthquake counts
        self.countries = []     # (name, [pixel rings], bbox, polys)
        with open(os.path.join(render.DATA_DIR,
                               "world-countries.json")) as f:
            geojson = json.load(f)
        for feature in geojson["features"]:
            name = feature["properties"].get("name")
            if not name:
                continue
            rings_px = []
            for ring in render._rings(feature["geometry"]):
                pts = [self.proj.xy(lon, lat) for lon, lat in ring]
                if len(pts) >= 3:
                    rings_px.append(pts)
            polys = []
            g = feature["geometry"]
            if g["type"] == "Polygon":
                polys.append(g["coordinates"][0])
            elif g["type"] == "MultiPolygon":
                polys.extend(p[0] for p in g["coordinates"])
            if not polys:
                continue
            lons = [p[0] for ring in polys for p in ring]
            lats = [p[1] for ring in polys for p in ring]
            bbox = (min(lons), min(lats), max(lons), max(lats))
            self.countries.append((name, rings_px, bbox, polys))

    # -- the live statistic --------------------------------------

    @property
    def fetch_s(self):
        return 1800 if self.quakes is not None else 60

    def refresh_data(self):
        req = urllib.request.Request(
            QUAKES_URL, headers={"User-Agent": "ledwall"})
        with urllib.request.urlopen(req, timeout=45) as r:
            doc = json.loads(r.read().decode("utf-8"))
        counts = {}
        for feat in doc.get("features", []):
            coords = feat.get("geometry", {}).get("coordinates")
            if not coords:
                continue
            lon, lat = coords[0], coords[1]
            for name, _px, bbox, polys in self.countries:
                if bbox[0] <= lon <= bbox[2] and \
                        bbox[1] <= lat <= bbox[3] and \
                        render._inside_polys(lon, lat, polys):
                    counts[name] = counts.get(name, 0) + 1
                    break
        self.quakes = counts
        self._qversion += 1

    # -- frame building -------------------------------------------

    def _values(self, key):
        if key == "quakes":
            return dict(self.quakes or {})
        return self.data.get(key, {})

    def _prepare(self, idx):
        key = STATS[idx][0]
        cache_key = (key, self._qversion if key == "quakes" else 0)
        if cache_key in self._prepared:
            return self._prepared[cache_key]
        _k, _h, scale, ramp, fmt, domain, _s = STATS[idx]
        values = self._values(key)
        positives = [v for v in values.values() if v and v > 0]
        if domain is not None:
            lo_v, hi_v = domain
        elif positives:
            lo_v, hi_v = min(positives), max(positives)
        else:
            lo_v, hi_v = 0, 1
        fills = {}
        for name, v in values.items():
            if v is None or (scale == "log" and v <= 0):
                continue  # a true zero still plots on a linear
                # scale (0% internet is a fact, not a gap)
            if scale == "log":
                t = (math.log10(v) - math.log10(lo_v)) / \
                    max(1e-9, math.log10(hi_v) - math.log10(lo_v))
            else:
                t = (v - lo_v) / max(1e-9, hi_v - lo_v)
            t = min(1.0, max(0.0, t)) ** 0.75
            fills[name] = _lerp(ramp[0], ramp[1], t)
        top = sorted(values.items(), key=lambda kv: -kv[1])[:3]
        kit = {"fills": fills, "lo_label": fmt(lo_v),
               "hi_label": fmt(hi_v), "ramp": ramp,
               "top": top, "fmt": fmt, "count": len(fills)}
        self._prepared[cache_key] = kit
        return kit

    def _frame(self, idx):
        key = (idx, self._qversion if STATS[idx][0] == "quakes"
               else 0)
        if key in self._frames:
            return self._frames[key]
        _k, headline, _sc, _r, _f, _d, source = STATS[idx]
        kit = self._prepare(idx)
        img = Image.new("RGB", (CANVAS_W, CANVAS_H), (4, 6, 10))
        d = ImageDraw.Draw(img)
        for name, rings_px, _bbox, _polys in self.countries:
            fill = kit["fills"].get(name, NO_DATA_FILL)
            for pts in rings_px:
                d.polygon(pts, fill=fill, outline=BORDER)
        f_t = _font(11)
        f_s = _font(9)
        d.text((5, 4), headline, font=f_t, fill=TITLE_C)
        # legend: ramp bar with the scale's ends, and the
        # no-data swatch, just above the strip
        ramp = kit["ramp"]
        for i in range(110):
            d.line((5 + i, CANVAS_H - 42, 5 + i, CANVAS_H - 37),
                   fill=_lerp(ramp[0], ramp[1], i / 109))
        d.text((5, CANVAS_H - 35), kit["lo_label"], font=f_s,
               fill=LABEL)
        hi_w = d.textlength(kit["hi_label"], font=f_s)
        d.text((115 - hi_w, CANVAS_H - 35), kit["hi_label"],
               font=f_s, fill=LABEL)
        d.rectangle((124, CANVAS_H - 41, 130, CANVAS_H - 36),
                    fill=NO_DATA_FILL, outline=BORDER)
        d.text((134, CANVAS_H - 35), "NO DATA", font=f_s,
               fill=LABEL)
        # strip: the leaders, the source, the position
        d.rectangle((0, CANVAS_H - 26, CANVAS_W, CANVAS_H),
                    fill=STRIP_BG + (238,))
        parts = ["%s %s" % (SHORT.get(n, n).upper(), kit["fmt"](v))
                 for n, v in kit["top"]]
        line1 = ""
        for n in range(len(parts), 0, -1):
            cand = " · ".join(parts[:n])
            if d.textlength(cand, font=f_s) <= 205:
                line1 = cand
                break
        d.text((5, CANVAS_H - 24), line1, font=f_s, fill=VALUE)
        pos = "%d / %d" % (idx + 1, len(STATS))
        d.text((CANVAS_W - 5 - d.textlength(pos, font=f_s),
                CANVAS_H - 24), pos, font=f_s, fill=LABEL)
        year = self.years.get(STATS[idx][0])
        src = source.replace("{year}", str(year or "")).replace(
            "  ", " ")
        d.text((5, CANVAS_H - 12), src, font=f_s, fill=LABEL)
        self._frames[key] = img
        return img

    # -- the cycle -------------------------------------------------

    def draw(self, ctx):
        stat_s = float(self.cfg.get("atlas_stat_s", 35))
        elapsed = time.time() - self.t0
        idx = int(elapsed // stat_s) % len(STATS)
        phase = elapsed % stat_s
        kit = self._prepare(idx)
        self.dot_count = kit["count"]
        img = self._frame(idx)
        if phase > stat_s - FADE_S:
            nxt = (idx + 1) % len(STATS)
            t = (phase - (stat_s - FADE_S)) / FADE_S
            img = Image.blend(img, self._frame(nxt),
                              t * t * (3 - 2 * t))
        return img
